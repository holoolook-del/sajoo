/**
 * 심리 테스트 콘텐츠 DB — 설문형. 허브 /test에서 목록으로 제공.
 * - mbti: 4축(E/I·S/N·T/F·J/P) 16문항 → 16타입 + 축별 비율·궁합 타입
 * - job: 홀랜드 RIASEC 6형 12문항 → 상위 2형 + 6형 분포·추천 직업
 * - love: 3축(속도·거리·표현) 12문항 → 6 연애 유형
 * - animal: 3축(사회성·해결·에너지) 12문항 → 6 본능 동물
 * - color: 6색 자유 배점 12문항 → 성격 색
 * - stress: 12문 hi/lo 체크 → 4단계 스트레스 게이지 (절대값 바)
 * 결과문은 전문 진단이 아닌 재미·자기표현용 자체 제작.
 */

export interface QuizQuestion {
  text: string;
  choices: { label: string; w: string }[]; // w = 가중치 키 (축 글자 or 유형 코드)
}

export interface QuizResultType {
  code: string;
  name: string;
  desc: string;
  tags: string[];
  accent?: string;
  jobs?: string[];
  /** 잘 맞는 타입 / 부딪히기 쉬운 타입 */
  good?: string[];
  hard?: string[];
  watch?: string; // 주의할 점
  /** 강점 3줄 */
  strong?: string[];
  /** 상황별 해석 — "연애할 때"·"일할 때" 등 */
  scenes?: { label: string; text: string }[];
}

/** 축별 막대 표시 설정 — MBTI: 4축 대립 바 / 직업성향: 6형 분포 바 */
export interface AxisBar {
  a: string; // 키
  b?: string; // 대립 키 (없으면 a 단일 퍼센트 바)
  label: string;
  /** 단일 바의 만점 기준 (기본: 전체 바 중 최고 득점). 스트레스 지수처럼 절대값 표시할 때 사용 */
  max?: number;
}

export interface QuizDef {
  id: string;
  title: string;
  subtitle: string;
  /** 허브 목록에 표시할 썸네일 파일명 (public/assets/illust/<img>.webp) */
  img: string;
  questions: QuizQuestion[];
  resolve: (score: Record<string, number>) => string;
  types: Record<string, QuizResultType>;
  /** 결과 아래에 그리는 점수 바 */
  bars?: AxisBar[];
  /** 두 번째 유형도 결과 제목에 붙일지 (직업성향: 상위 2형) */
  secondCode?: (score: Record<string, number>) => string | null;
  /** 근거·출처 한 줄 — 인트로와 결과 하단에 표시해 신뢰감을 준다 */
  note?: string;
  /** 결과 확신도 — 득표 차이가 작아 경계선일 때 '보통/낮음'으로 안내 */
  confidence?: (score: Record<string, number>) => { level: 'high' | 'mid' | 'low'; text: string };
  /** 중간 선택지 라벨 — 설정하면 매 문항에 '모르겠다' 버튼이 붙어 억지 양택 노이즈를 막음 */
  neutral?: string;
  shareLabel: string;
}

/** 축별 대립 문항의 경계선 판정 — |a-b| <= 1이면 거의 비슷한 축 */
export function borderlineAxes(bars: AxisBar[], score: Record<string, number>): string[] {
  return bars
    .filter((b) => b.b && Math.abs((score[b.a] ?? 0) - (score[b.b] ?? 0)) <= 1)
    .map((b) => b.label);
}

