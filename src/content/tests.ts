function mbtiResolve(score: Record<string, number>): string {
  return (
    (score.E ?? 0) >= (score.I ?? 0) ? 'E' : 'I'
  ) + (
    (score.S ?? 0) >= (score.N ?? 0) ? 'S' : 'N'
  ) + (
    (score.T ?? 0) >= (score.F ?? 0) ? 'T' : 'F'
  ) + (
    (score.J ?? 0) >= (score.P ?? 0) ? 'J' : 'P'
  );
}

