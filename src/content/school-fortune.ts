export interface SchoolLuck {
  cat: SchoolCat;
  grade: Grade;
  stars: number;
  msg: string;
}

/** FNV-1a 해시 — 날짜+항목을 시드로 써서 같은 날 모두 같은 결과 */
function seedOf(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** date('YYYY-MM-DD') 기준 4개 운세 반환 — 결정적, 저장 불필요 */
export function schoolFortune(date: string): SchoolLuck[] {
  return SCHOOL_CATS.map((cat) => {
    const h = seedOf(`${date}:${cat.id}`);
    const g = SCHOOL_GRADES[h % SCHOOL_GRADES.length]!;
    const pool = MSGS[cat.id]![g.grade]!;
    return {
      cat,
      grade: g.grade,
      stars: g.stars,
      msg: pool[Math.floor(h / SCHOOL_GRADES.length) % pool.length]!,
    };
  });
}

/** 4개 운세 평균 별점 → 한 줄 총평 */
export function schoolSummary(lucks: SchoolLuck[]): { stars: number; text: string } {
  const avg = lucks.reduce((a, l) => a + l.stars, 0) / lucks.length;
  if (avg >= 4.5) return { stars: 5, text: '오늘은 레전드급 하루 — 뭐든 잘 풀려!' };
  if (avg >= 3.5) return { stars: 4, text: '좋은 하루! 웃을 일이 생길 거야' };
  if (avg >= 2.5) return { stars: 3, text: '평범한 하루 — 소소한 재미를 찾아봐' };
  if (avg >= 1.5) return { stars: 2, text: '조심스러운 하루 — 침착하면 괜찮아' };
  return { stars: 1, text: '험난한 날 — 웃으며 넘기는 게 진짜 고수!' };
}
